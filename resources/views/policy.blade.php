        <li><strong>Farm data</strong> — name, location, palm tree count, area, variety, tree age, planting date, soil type, water source, water analysis, and any notes added by the engineer.</li>
        <li><strong>Task and visit data</strong> — schedules, status, and notes related to engineer visits and farm care tasks.</li>
        <li><strong>Photos and videos</strong> — uploaded by the farmer as evidence of completed tasks.</li>
        <li><strong>Device notification token (FCM Token)</strong> — used to send push notifications to your phone (schedule reminders, status updates).</li>
        <li><strong>Subscription data</strong> — the farm's renewal cycle and upcoming payment date.</li>
      </ul>
    </section>

    <section>
      <h3>3. How We Use Your Data</h3>
